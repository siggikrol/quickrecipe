const assert = require('node:assert/strict');
const P = require('./canteen-model');
const week = P.create('2026-09-16');
assert.equal(week.start, '2026-09-14');
assert.equal(P.monday('2027-01-01'), '2026-12-28');
assert.equal(P.shift('2026-03-29', 1), '2026-03-30');
assert.throws(() => P.create('2026-02-30'));
const day = week.days[0]; day.defaultPortions = 355;
const main = P.add(day, week.slots[1].id, 'chicken');
assert.equal(P.portions(main, day), 355);
main.portions = 330;
const vegetable = P.add(day, week.slots[1].id, 'vegetables'); vegetable.portions = 25;
assert.equal(P.totals(day.items, day).mismatch, false);
vegetable.portions = 0;
assert.equal(P.totals(day.items, day).total, 330);
assert.equal(P.totals(day.items, day).mismatch, true);
assert.throws(() => P.count(-1)); assert.throws(() => P.count(1.5));
day.note = 'Serve at 12:30';
week.production[main.id] = { completed: true };
const copied = P.copyWeek(week, '2026-09-30');
assert.equal(copied.start, '2026-09-28');
assert.equal(copied.days[0].note, day.note);
assert.notEqual(copied.days[0].items[0].id, main.id);
assert.deepEqual(copied.production, {});
copied.days[0].items[0].portions = 5;
assert.equal(main.portions, 330);
P.copyDay(day, week.days[3]);
assert.notEqual(week.days[3].items[0].id, main.id);
assert.equal(week.days[3].note, day.note);
assert.equal(P.selected(week, [day.date], week.slots[1].id).length, 2);
assert.deepEqual(P.validate(JSON.parse(JSON.stringify(week))), week);
const invalid = JSON.parse(JSON.stringify(week)); invalid.production.bad = { batch: { mode: 'maximum', value: 0 } };
assert.throws(() => P.validate(invalid));
console.log('Canteen planning: dates, defaults, zero overrides, variants, copying and persistence passed.');
