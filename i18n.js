// Some browsers omit Icelandic sorting rules from their locale data.
const hasIcelandicCollation = Intl.Collator.supportedLocalesOf(['is']).length > 0;
const icelandicLetterOrder = 'aábcdðeéfghiíjklmnoópqrstuúvwxyýzþæö';
function compareIcelandicLabels(left, right) {
  const letters = text => [...String(text).normalize('NFC').toLowerCase()];
  const rank = letter => {
    let index = icelandicLetterOrder.indexOf(letter);
    if (index < 0) index = icelandicLetterOrder.indexOf(letter.normalize('NFD')[0]);
    return index < 0 ? letter.codePointAt(0) : 65536 + index;
  };
  const a = letters(left), b = letters(right);
  for (let i = 0; i < Math.min(a.length, b.length); i++) {
    const difference = rank(a[i]) - rank(b[i]);
    if (difference) return difference;
  }
  return a.length - b.length;
}
function compareRecipeLabels(left, right, locale = language) {
  if (locale === 'is' && !hasIcelandicCollation) return compareIcelandicLabels(left, right);
  return left.localeCompare(right, locale, { sensitivity: 'base' });
}

function recipeCount(n) {
  const form = new Intl.PluralRules(language).select(n);
  const words = { en: {one:'recipe',other:'recipes'}, pl:{one:'przepis',few:'przepisy',many:'przepisów',other:'przepisu'}, is:{one:'uppskrift',other:'uppskriftir'} };
  return `${n} ${words[language][form] || words[language].other}`;
}
let recipeTranslations = { pl: {}, is: {} };
let hasRecipeTranslationFallback = false;
async function loadRecipeTranslations(version) {
  await Promise.all(['pl', 'is'].map(async lang => {
    try {
      const response = await fetch(`./translations/${lang}.json?v=${version}`);
      if (!response.ok) throw new Error('Translation download failed');
      const data = await response.json();
      if (!data || Array.isArray(data) || typeof data !== 'object' || Object.values(data).some(v => typeof v !== 'string' || !v.trim())) throw new Error('Invalid translations');
      recipeTranslations[lang] = data;
    } catch (error) { console.warn(`Could not load ${lang} recipe translations`, error); }
  }));
}
function recipeText(text) {
  return language === 'en' ? text : recipeTranslations[language]?.[text] || text;
}
function missingRecipeTranslation(r) {
  if (!r || language === 'en') return false;
  return [r.title, r.desc, ...r.ingredients.map(i => cleanIngredientName(i[0])), ...r.steps,
    r.prep, r.cook, r.bake, r.ferment, r.yield].filter(Boolean).some(text => !recipeTranslations[language]?.[text]);
}
function translatedYield(value) {
  const scaled = yieldText(value);
  if (language === 'en') return scaled;
  const translated = recipeText(value);
  if (translated === value) return scaled;
  const numbers = scaled.match(/\d+(?:\.\d+)?/g) || [];
  let index = 0;
  let result = translated.replace(/\d+(?:[.,]\d+)?/g, number => numbers[index++] ?? number);
  // Re-inflect common count nouns after scaling, without touching pan dimensions.
  const forms = language === 'pl' ? [
    ['porcja','porcje','porcji'], ['bochenek','bochenki','bochenków'],
    ['bułka','bułki','bułek'], ['bułeczka','bułeczki','bułeczek'],
    ['kawałek','kawałki','kawałków'], ['szklanka','szklanki','szklanek'],
    ['ciasto','ciasta','ciast'], ['blacha','blachy','blach'],
    ['bagietka','bagietki','bagietek'], ['forma','formy','form']
  ] : [
    ['skammtur','skammtar'], ['brauðhleifur','brauðhleifar'], ['hleifur','hleifar'],
    ['bolla','bollur'], ['snúður','snúðar'], ['kaka','kökur'], ['glas','glös'],
    ['sneið','sneiðar'], ['ofnskúffa','ofnskúffur'], ['skál','skálar']
  ];
  const plural = new Intl.PluralRules(language);
  if (language === 'pl') {
    result = result.replace(/(\d+(?:[.,]\d+)?)\s+(?:duży|duże|dużych)\s+(?:bochenek|bochenki|bochenków)/gu, (_, n) => {
      const form = plural.select(Number(n.replace(',', '.')));
      return n + (form === 'one' ? ' duży bochenek' : form === 'few' ? ' duże bochenki' : ' dużych bochenków');
    });
  } else {
    result = result.replace(/(\d+(?:[.,]\d+)?)\s+(?:stór|stórir)\s+(?:brauðhleifur|brauðhleifar)/gu, (_, n) => n + (plural.select(Number(n.replace(',', '.'))) === 'one' ? ' stór brauðhleifur' : ' stórir brauðhleifar'));
  }
  for (const words of forms) {
    const pattern = new RegExp(`(\\d+(?:[.,]\\d+)?)(\\s+)(?:${words.join('|')})(?=$|[\\s/,.])`, 'gu');
    result = result.replace(pattern, (_, number, space) => {
      const form = plural.select(Number(number.replace(',', '.')));
      const word = words[form === 'one' ? 0 : language === 'pl' && form !== 'few' ? 2 : 1];
      return number + space + word;
    });
  }
  return result;
}
function unitLabel(unitName, amount) {
  if (language === 'en') return unitName;
  const units = {
    pl: {capful:amount === 1 ? 'nakrętka' : 'nakrętki', drops:'krople', pc:'szt.', tsp:'łyżeczki', tbsp:'łyżki', cup:'szkl.', sachet:'saszetki', handful:'garść', bunch:'pęczek', pinch:'szczypta', 'as needed':'według potrzeb'},
    is: {capful:amount === 1 ? 'tappi' : 'tappar', drops:'dropar', pc:'stk.', tsp:'tsk.', tbsp:'msk.', cup:amount === 1 ? 'bolli' : 'bollar', sachet:'bréf', handful:'handfylli', bunch:'búnt', pinch:'klípa', 'as needed':'eftir þörfum'}
  };
  if (units[language][unitName]) return units[language][unitName];
  const pack = unitName.match(/^(.*?) \(size unspecified\)$/);
  if (pack) {
    const names = {pl:{roll:'rolka',rolls:'rolki',container:'opakowanie',jar:'słoik',bag:'torebka',bags:'torebki',box:'pudełko',boxes:'pudełka',pack:'opakowanie',tub:'pojemnik',tubs:'pojemniki',packet:'opakowanie'},is:{roll:'rúlla',rolls:'rúllur',container:'ílát',jar:'krukka',bag:'poki',bags:'pokar',box:'kassi',boxes:'kassar',pack:'pakki',tub:'dós',tubs:'dósir',packet:'pakki'}};
    return `${names[language][pack[1]] || pack[1]} (${language === 'pl' ? 'niepodany rozmiar' : 'stærð ótilgreind'})`;
  }
  return unitName;
}
const translatedNodes = new WeakMap();
const translatedAttributes = new WeakMap();
function translateInterface() {
  if (!document?.documentElement) return;
  document.documentElement.lang = language;
  for (const button of document.querySelectorAll('[data-language]')) button.setAttribute('aria-pressed', String(button.dataset.language === language));
  const note = document.getElementById('languageNote');
  if (note) note.hidden = language === 'en' || !hasRecipeTranslationFallback;
  // Translate only interface containers, never recipe prose or editor values.
  const roots = document.querySelectorAll('.top, .toolbar, .browse-nav, #chips, .recipe-nav, #modalBackdrop, #toast, #languageNote, .card .stat:not(.timing-stat), .card .tag, .detail-head .tag, .timing-stat, .hydration-box, .detail-actions, #detailFav, .pane > h2, .ingredients-heading, .focus-hint, .empty, .loading');
  for (const root of roots) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (node.parentElement.closest('option, textarea, script, #resultSummary')) continue;
      const previous = translatedNodes.get(node);
      const original = previous && node.nodeValue === previous.output ? previous.original : node.nodeValue;
      const key = original.trim();
      let result = t(key);
      if (result === key) {
        const timing = key.match(/^(Prep|Cook|Bake|Rest|Method)(\s.*)$/s);
        if (timing) result = t(timing[1]) + timing[2];
        if (key.startsWith('Adjusts the liquid automatically. Recipe range: ')) result = ({en:'Adjusts the liquid automatically. Recipe range: ',pl:'Automatycznie dostosowuje ilość płynu. Zakres przepisu: ',is:'Stillir vökvamagn sjálfkrafa. Bil uppskriftar: '}[language]) + key.split('Recipe range: ')[1];
        if (key.includes('% hydration')) result = key.replace('hydration', t('hydration')).replace(/^([^·]+)( ·)/, (_,cat,sep)=>t(cat.trim())+sep);
      }
      const output = original.replace(key, result);
      translatedNodes.set(node, {original, output});
      if (node.nodeValue !== output) node.nodeValue = output;
    }
  }
  for (const el of document.querySelectorAll('[aria-label], [title], [placeholder]')) {
    const saved = translatedAttributes.get(el) || {};
    for (const attr of ['aria-label','title','placeholder']) {
      if (!el.hasAttribute(attr)) continue;
      const value=el.getAttribute(attr), prev=saved[attr];
      const original=prev && value===prev.output ? prev.original : value;
      const output=t(original); saved[attr]={original,output};
      if(value!==output) el.setAttribute(attr,output);
    }
    translatedAttributes.set(el,saved);
  }
}
function changeLanguage(value) {
  if (!['en','pl','is'].includes(value)) return;
  language = value;
  try { localStorage.setItem(LANGUAGE_KEY, language); } catch {}
  const detail = document.getElementById('detail');
  const scroll = detail.scrollTop, pageScroll = window.scrollY;
  document.getElementById('sections').innerHTML = '';
  document.getElementById('chips').innerHTML = '';
  render();
  for (const option of document.querySelectorAll('#fSection option')) {
    const section = recipeSections.find(s => s.id === option.value);
    if (section) option.textContent = t(section.label);
  }
  translateInterface();
  detail.scrollTop = scroll;
  window.scrollTo(0, pageScroll);
}
const interfaceObserver = new MutationObserver(translateInterface);
interfaceObserver.observe(document.body, {childList:true,subtree:true,characterData:true});
document.querySelectorAll('[data-language]').forEach(button => button.addEventListener('click', () => changeLanguage(button.dataset.language)));
translateInterface();
